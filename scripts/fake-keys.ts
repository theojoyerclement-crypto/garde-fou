/**
 * Random, syntactically valid FAKE keys, built at runtime.
 *
 * No complete key is ever written in this repository: prefixes are assembled
 * from fragments so neither GitHub push protection nor Garde-Fou itself
 * flags the source. Never commit the output of these functions.
 */
import { randomBytes, randomInt } from 'node:crypto';

const ALNUM = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const URLSAFE = `${ALNUM}-_`;

function randomFrom(alphabet: string, length: number): string {
  let s = '';
  for (let i = 0; i < length; i++) s += alphabet[randomInt(alphabet.length)];
  return s;
}

function b64url(obj: unknown): string {
  return Buffer.from(JSON.stringify(obj)).toString('base64url');
}

const SK = ['s', 'k'].join('');

export function fakeOpenAIKey(): string {
  return [SK, 'proj', randomFrom(URLSAFE, 156)].join('-');
}

export function fakeAnthropicKey(): string {
  return [SK, 'ant', ['api', '03'].join(''), `${randomFrom(URLSAFE, 93)}AA`].join('-');
}

export function fakeStripeLiveKey(): string {
  return [SK, 'live', randomFrom(ALNUM, 99)].join('_');
}

function fakeSupabaseJwt(role: 'service_role' | 'anon'): string {
  const now = Math.floor(Date.now() / 1000);
  return [
    b64url({ alg: 'HS256', typ: 'JWT' }),
    b64url({ iss: 'supabase', ref: randomFrom('abcdefghijklmnopqrst', 20), role, iat: now, exp: now + 10 * 365 * 86400 }),
    randomBytes(32).toString('base64url'),
  ].join('.');
}

export function fakeSupabaseServiceRoleKey(): string {
  return fakeSupabaseJwt('service_role');
}

/** Public by design: must NOT be reported. */
export function fakeSupabaseAnonKey(): string {
  return fakeSupabaseJwt('anon');
}

/** Low-entropy look-alike: must NOT be reported. */
export function placeholderStripeKey(): string {
  return [SK, 'live', 'x'.repeat(32)].join('_');
}

/** Test-mode key: must NOT be reported. */
export function fakeStripeTestKey(): string {
  return [SK, 'test', randomFrom(ALNUM, 99)].join('_');
}

/** Publishable key: must NOT be reported. */
export function fakeStripePublishableKey(): string {
  return [['p', 'k'].join(''), 'live', randomFrom(ALNUM, 99)].join('_');
}

export interface GeneratedSecrets {
  openai: string;
  anthropic: string;
  stripe: string;
  supabaseServiceRole: string;
  /** Path (relative to the fixture root) → content. */
  files: Record<string, string>;
}

/** Files with fake secrets that complete fixtures/vulnerable-app. */
export function generateFixtureSecrets(): GeneratedSecrets {
  const openai = fakeOpenAIKey();
  const anthropic = fakeAnthropicKey();
  const stripe = fakeStripeLiveKey();
  const supabaseServiceRole = fakeSupabaseServiceRoleKey();

  const files: Record<string, string> = {
    '.env': [
      '# Generated by `npm run fixture` — FAKE keys, do not commit.',
      `OPENAI_API_KEY=${fakeOpenAIKey()}`,
      `SUPABASE_SERVICE_ROLE_KEY=${fakeSupabaseServiceRoleKey()}`,
      `NEXT_PUBLIC_STRIPE_SECRET_KEY=${fakeStripeLiveKey()}`,
      `NEXT_PUBLIC_SUPABASE_ANON_KEY=${fakeSupabaseAnonKey()}`,
      '',
    ].join('\n'),
    'src/lib/ai.generated.ts': [
      '// Generated by `npm run fixture` — FAKE keys, do not commit.',
      "import OpenAI from 'openai';",
      "import Anthropic from '@anthropic-ai/sdk';",
      '',
      `export const openai = new OpenAI({ apiKey: '${openai}' });`,
      `export const anthropic = new Anthropic({ apiKey: "${anthropic}" });`,
      '',
    ].join('\n'),
    'src/lib/payments.generated.ts': [
      '// Generated by `npm run fixture` — FAKE keys, do not commit.',
      "import Stripe from 'stripe';",
      "import { createClient } from '@supabase/supabase-js';",
      '',
      `export const stripe = new Stripe('${stripe}');`,
      `export const admin = createClient('https://example.supabase.co', '${supabaseServiceRole}');`,
      `// Test and placeholder keys are fine: ${fakeStripeTestKey()} ${placeholderStripeKey()}`,
      '',
    ].join('\n'),
  };

  return { openai, anthropic, stripe, supabaseServiceRole, files };
}
